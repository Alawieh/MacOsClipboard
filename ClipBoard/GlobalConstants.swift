let PASTE_KEYSTROKE_DELAY = Duration.milliseconds(80)
/// Pasteboard markers set by password managers and other apps that ask not to be recorded
/// (nspasteboard.org convention).
let PASTEBOARD_IGNORED_TYPES: Set<String> = [
