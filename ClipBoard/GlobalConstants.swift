// MARK: - History

/// Unpinned items kept before the oldest are dropped. Pinned items never count toward this.
let HISTORY_MAX_UNPINNED_ITEMS = 100
/// Copies with more characters than this are left out of history (they stay on the system clipboard).
let HISTORY_MAX_TEXT_LENGTH = 1_000_000
/// Images, videos and audio bigger than this are left out of history (they stay on the system clipboard).
let HISTORY_MAX_MEDIA_BYTES = 100 * 1024 * 1024
let HISTORY_FOLDER_NAME = "ClipBoard"
let HISTORY_FILE_NAME = "history.json"
let HISTORY_MEDIA_FOLDER_NAME = "media"
/// Thumbnails are rendered at this many points per side (rows show them at 32 pt, so 2x for sharpness).
let HISTORY_THUMBNAIL_SIDE: CGFloat = 64

// MARK: - Pasteboard

let PASTEBOARD_POLL_INTERVAL = Duration.milliseconds(400)
